//! The spheres and their rules about providers, from the assistant's central configuration.
//!
//! The gateway reads the part of the central configuration that `config-apply` renders for a
//! service: `version = 1` and a `[spheres.<name>]` table per sphere, whose optional
//! `rules.llm` lists the only providers that may receive the sphere's content. Keys the
//! gateway does not need (descriptions, the wiki rule) are ignored, as the format allows.

use std::collections::HashMap;
use std::path::Path;

use serde::Deserialize;

/// The format versions this reader understands.
const VERSIONS: &[i64] = &[1];

/// The declared spheres and which providers each may use.
#[derive(Debug, Clone, Default)]
pub struct Spheres(HashMap<String, Option<Vec<String>>>);

/// Why a sphere may not use a provider.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum SphereError {
    #[error("the sphere {0:?} is not declared in the configuration")]
    Unknown(String),
    #[error("the rules of sphere {sphere:?} do not allow the provider {provider:?}")]
    ProviderNotAllowed { sphere: String, provider: String },
}

#[derive(Deserialize)]
struct File {
    version: i64,
    spheres: HashMap<String, Sphere>,
}

#[derive(Deserialize)]
struct Sphere {
    #[serde(default)]
    rules: Rules,
}

#[derive(Deserialize, Default)]
struct Rules {
    llm: Option<Vec<String>>,
}

impl Spheres {
    pub fn load(path: &Path) -> Result<Self, String> {
        let text = std::fs::read_to_string(path)
            .map_err(|err| format!("reading {}: {err}", path.display()))?;
        Self::parse(&text).map_err(|err| format!("{}: {err}", path.display()))
    }

    pub fn parse(text: &str) -> Result<Self, String> {
        let file: File = toml::from_str(text).map_err(|err| err.message().to_string())?;
        if !VERSIONS.contains(&file.version) {
            return Err(format!(
                "version {} is not supported; this gateway reads version {}",
                file.version, VERSIONS[0]
            ));
        }
        if file.spheres.is_empty() {
            return Err("no spheres are declared".into());
        }
        for name in file.spheres.keys() {
            if !crate::is_name(name) {
                return Err(format!("{name:?} is not a sphere name"));
            }
        }
        Ok(Spheres(
            file.spheres
                .into_iter()
                .map(|(name, sphere)| (name, sphere.rules.llm))
                .collect(),
        ))
    }

    /// Whether content of `sphere` may go to `provider`.
    pub fn check(&self, sphere: &str, provider: &str) -> Result<(), SphereError> {
        match self.0.get(sphere) {
            None => Err(SphereError::Unknown(sphere.to_string())),
            Some(Some(allowed)) if !allowed.iter().any(|p| p == provider) => {
                Err(SphereError::ProviderNotAllowed {
                    sphere: sphere.to_string(),
                    provider: provider.to_string(),
                })
            }
            Some(_) => Ok(()),
        }
    }

    pub fn names(&self) -> impl Iterator<Item = &str> {
        self.0.keys().map(String::as_str)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// As `config-apply` renders it, plus a sphere that allows no provider.
    const RENDERED: &str = r#"
# Generated by config-apply from the central assistant configuration; do not edit.
version = 1

[spheres.work]
description = "Employer, projects, colleagues"

[spheres.work.rules]
wiki = "never"
llm = ["mistral"]

[spheres.private]
description = "Family, home, finances"

[spheres.clubs]
rules = { wiki = "allowed", llm = [] }
"#;

    #[test]
    fn applies_the_rules_of_the_rendered_configuration() {
        let spheres = Spheres::parse(RENDERED).unwrap();
        assert_eq!(spheres.check("work", "mistral"), Ok(()));
        assert_eq!(
            spheres.check("work", "openai"),
            Err(SphereError::ProviderNotAllowed {
                sphere: "work".into(),
                provider: "openai".into()
            })
        );
        // Without an llm rule, every provider is allowed.
        assert_eq!(spheres.check("private", "openai"), Ok(()));
        // An empty list allows none.
        assert!(spheres.check("clubs", "mistral").is_err());
        assert_eq!(
            spheres.check("hobbies", "mistral"),
            Err(SphereError::Unknown("hobbies".into()))
        );
    }

    #[test]
    fn rejects_files_it_does_not_understand() {
        for (text, expected) in [
            (
                "version = 2\n[spheres.work]\n",
                "version 2 is not supported",
            ),
            ("[spheres.work]\n", "missing field `version`"),
            ("version = 1\n", "missing field `spheres`"),
            ("version = 1\n[spheres]\n", "no spheres"),
            ("version = 1\n[spheres.Work]\n", "not a sphere name"),
            (
                "version = 1\n[spheres.work]\nrules = { llm = \"mistral\" }\n",
                "invalid type",
            ),
        ] {
            let err = Spheres::parse(text).unwrap_err();
            assert!(err.contains(expected), "{text:?}: {err}");
        }
    }
}
